#!/usr/bin/env node
// Reproduce MSVC file-scope tags and COMDAT inline linkage for Linux C.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export function sourceFiles(roots) {
  const files = [];
  function walk(root) {
    for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
      const filename = path.join(root, entry.name);
      if (entry.isDirectory()) walk(filename);
      else if (['.c', '.h', '.inl'].includes(path.extname(filename).toLowerCase()) && fs.statSync(filename).isFile()) files.push(filename);
    }
  }
  for (const root of roots) {
    const start = files.length;
    walk(root);
    files.splice(start, files.length - start, ...files.slice(start).sort());
  }
  return files;
}

export function stripCplusplus(text) {
  const kept = [], stack = [];
  const unused = '(?:__cplusplus|_WIN64)\\b';
  const cpp = new RegExp('^#\\s*if(?:def\\s+' + unused + '|\\s+defined\\s*\\(?\\s*' + unused + ')');
  const c = new RegExp('^#\\s*if(?:ndef\\s+' + unused + '|\\s+!\\s*defined\\s*\\(?\\s*' + unused + ')');
  const lines = text.split(/\r\n|[\n\r\v\f\x1c-\x1e\x85\u2028\u2029]/);
  if (lines.at(-1) === '') lines.pop();
  for (const line of lines) {
    const directive = line.trim().replace(/^#\s*/, '#');
    if (directive.startsWith('#if')) { stack.push([cpp.test(directive) ? 'cpp' : c.test(directive) ? 'c' : 'other', false]); continue; }
    if (directive.startsWith('#else') && stack.length) { stack.at(-1)[1] = true; continue; }
    if (directive.startsWith('#elif') && stack.length) { stack[stack.length - 1] = ['other', false]; continue; }
    if (directive.startsWith('#endif') && stack.length) { stack.pop(); continue; }
    if (!stack.some(([kind, inElse]) => (kind === 'cpp' && !inElse) || (kind === 'c' && inElse))) kept.push(line);
  }
  return kept.join('\n');
}
export function readSource(filename) {
  return stripCplusplus(fs.readFileSync(filename, 'latin1').replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, ' '));
}
export function scanTags(files) {
  const tags = new Map();
  for (const filename of files) for (const [, kind, name] of readSource(filename).matchAll(/\b(struct|union)\s+([A-Za-z_]\w*)/g)) {
    if (!tags.has(name)) tags.set(name, new Set());
    tags.get(name).add(kind);
  }
  return tags;
}
export function scanInlineFunctions(files, allInlines = false) {
  const texts = files.map(readSource), names = new Set();
  for (const text of texts) for (const [, name] of text.matchAll(/\b(?:__inline|_inline|__forceinline|D3DXINLINE|FORCEINLINE)\b[^;{}()]*?\b([A-Za-z_]\w*)\s*\([^;{}]*\)\s*\{/g)) names.add(name);
  const everything = texts.join('\n');
  return allInlines ? names : new Set([...names].filter(name => new RegExp('\\b' + name + '\\s*\\([^;{}]*\\)\\s*;').test(everything)));
}
export function render(tags, inlineFunctions) {
  const lines = ['/* generated by tools/linux_msvc_semantics.mjs - do not edit */', '#ifndef __HALO_LINUX_MSVC_SEMANTICS_H', '#define __HALO_LINUX_MSVC_SEMANTICS_H', '', '/* ---------- file-scope struct and union tags */', ''];
  for (const name of [...tags.keys()].sort()) if (tags.get(name).size === 1) lines.push(`${[...tags.get(name)][0]} ${name};`);
  lines.push('', '/* ---------- COMDAT inline functions */', '');
  for (const name of [...inlineFunctions].sort()) lines.push(`#pragma weak ${name}`);
  lines.push('', '#endif', '');
  return lines.join('\n');
}
export function main(args = process.argv.slice(2)) {
  if (args.includes('--help') || args.includes('-h')) {
    console.log('Usage: linux_msvc_semantics.mjs --output PATH [--tags DIRECTORY] [--inlines DIRECTORY] [--all-inlines]');
    return;
  }
  args = args.flatMap(arg => /^--(?:output|tags|inlines)=/.test(arg) ? [arg.slice(0, arg.indexOf('=')), arg.slice(arg.indexOf('=') + 1)] : [arg]);
  const tags = [], inlines = [];
  let output, allInlines = false;
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === '--all-inlines') allInlines = true;
    else if (['--output', '--tags', '--inlines'].includes(arg) && args[i + 1] && !args[i + 1].startsWith('--')) {
      const value = args[++i];
      if (arg === '--output') output = value;
      else (arg === '--tags' ? tags : inlines).push(value);
    } else throw new Error(`invalid argument: ${arg}`);
  }
  if (!output) throw new Error('--output is required');
  for (const root of [...tags, ...inlines]) if (!fs.existsSync(root) || !fs.statSync(root).isDirectory()) throw new Error(`${root} is not a directory`);
  const text = render(scanTags(sourceFiles(tags)), scanInlineFunctions(sourceFiles(inlines), allInlines));
  fs.mkdirSync(path.dirname(output), { recursive: true });
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== text) fs.writeFileSync(output, text, 'utf8');
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
